#!/usr/bin/env python3
"""Digest SECOP II HAR captures into a compact API contract for analysis.

Redacts JWTs/cookies so the output is safe to reason over and to commit.
"""
import json, glob, os, re, sys, collections
from urllib.parse import urlparse, parse_qs, unquote

HAR_DIR = sys.argv[1]
OUT = sys.argv[2]

JWT_RE = re.compile(r'eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}')
# The audit trail records the bidder's public IP on every action. It is STARCOOP's own
# network origin, adds nothing analytically, and should not sit in version control.
IPV4_RE = re.compile(r'\b(?:\d{1,3}\.){3}\d{1,3}\b')
SENSITIVE_HEADERS = {'authorization', 'cookie', 'set-cookie', 'x-xsrf-token'}

# STARCOOP's own company code. Ours may appear in the clear; everyone else's is a real
# Colombian NIT that resolves to a named company, so it gets a stable pseudonym. The
# platform anonymises rivals deliberately and decision D-09 forbids undoing that — a
# technical document is not a reason to accumulate a roster of who bid on what.
OWN_COMPANY = '700961121'
COMPANY_CODE_RE = re.compile(r'\b7\d{8}\b')
_pseudonyms = {}


def pseudonymise_company(code):
    code = str(code)
    if code == OWN_COMPANY:
        return code
    if code not in _pseudonyms:
        _pseudonyms[code] = f'<COMPETITOR_{len(_pseudonyms) + 1:02d}>'
    return _pseudonyms[code]


def redact(s):
    if not isinstance(s, str):
        return s
    s = JWT_RE.sub('<JWT_REDACTED>', s)
    s = IPV4_RE.sub('<IP_REDACTED>', s)
    return COMPANY_CODE_RE.sub(lambda m: pseudonymise_company(m.group(0)), s)


def is_noise(url):
    """Static assets, telemetry, third-party."""
    noise_hosts = ('gstatic.com', 'youtube.com', 'google.com', 'googletagmanager',
                   'doubleclick', 'ytimg.com', 'googleapis.com', 'gravatar')
    if any(h in url for h in noise_hosts):
        return True
    if '/StaticContent/' in url:
        return True
    if re.search(r'\.(js|css|png|jpg|jpeg|gif|svg|woff2?|ttf|ico|map|eot)(_v\d+)?($|\?)', url, re.I):
        return True
    return False


def main():
    entries = []
    for f in sorted(glob.glob(os.path.join(HAR_DIR, '*.har'))):
        try:
            d = json.load(open(f, encoding='utf-8'))
        except Exception as e:
            print(f'skip {f}: {e}', file=sys.stderr)
            continue
        for e in d['log']['entries']:
            e['_src'] = os.path.basename(f)
            entries.append(e)

    entries.sort(key=lambda e: e.get('startedDateTime', ''))

    out = []
    w = out.append

    w('# SECOP II e-Auction — Reverse-Engineered API Contract')
    w('')
    w('Digested from 5 HAR captures of a live `subasta inversa electronica`.')
    w('All JWTs/cookies redacted. Generated by `digest_har.py`.')
    w('')

    # ---- 1. Hosts
    hosts = collections.Counter()
    for e in entries:
        h = urlparse(e['request']['url']).netloc
        if not is_noise(e['request']['url']):
            hosts[h] += 1
    w('## 1. Hosts in play')
    w('')
    w('| Host | Non-static requests | Role |')
    w('|---|---:|---|')
    roles = {
        'community.secop.gov.co': 'Identity / STS — issues the JWT, hosts login + reCAPTCHA',
        'www.secop.gov.co': 'SECOP II main portal (CO1BusinessLine) — tender workspace',
        'subastas.secop.gov.co': 'e-Auction engine — REST API + SignalR realtime hub',
    }
    for h, c in hosts.most_common():
        w(f'| `{h}` | {c} | {roles.get(h, "")} |')
    w('')

    # ---- 2. REST endpoints on the auction API
    w('## 2. e-Auction REST API surface')
    w('')
    seen = collections.OrderedDict()
    for e in entries:
        u = e['request']['url']
        if 'eauctions.api' not in u:
            continue
        if '/signalr/' in u:
            continue
        path = urlparse(u).path.replace('/eauctions.api', '')
        key = (e['request']['method'], re.sub(r'/[0-9a-f]{8}-[0-9a-f-]{27,}', '/{auctionId}', path))
        key = (key[0], re.sub(r'/\d{6,}', '/{companyCode}', key[1]))
        if key not in seen:
            seen[key] = e

    for (method, path), e in seen.items():
        w(f'### `{method} {path}`')
        w('')
        qs = parse_qs(urlparse(e['request']['url']).query)
        if qs:
            w('Query params: ' + ', '.join(
                f'`{k}={"<JWT>" if k == "token" else redact(v[0])[:60]}`' for k, v in qs.items()))
            w('')
        pd = e['request'].get('postData', {}).get('text', '')
        if pd:
            w('Request body:')
            w('```json')
            try:
                w(json.dumps(json.loads(redact(pd)), indent=2, ensure_ascii=False)[:3000])
            except Exception:
                w(redact(unquote(pd))[:2000])
            w('```')
            w('')
        rc = e['response'].get('content', {}).get('text', '')
        if rc:
            w(f'Response ({e["response"]["status"]}):')
            w('```json')
            try:
                w(json.dumps(json.loads(redact(rc)), indent=2, ensure_ascii=False)[:4500])
            except Exception:
                w(redact(rc)[:2000])
            w('```')
            w('')

    # ---- 2b. The full GetAuction payload — the authoritative rule source.
    full = None
    for e in entries:
        if '/auction/GetAuction/' in e['request']['url']:
            try:
                full = json.loads(e['response']['content']['text'])
            except Exception:
                pass
            break
    if full:
        w('## 2b. The full `GetAuction` payload — READ THIS ONE, NOT `GetAuctionSimple`')
        w('')
        w('`GetAuctionSimple` returns opaque integer enums and **omits `minBidDifference`**.')
        w('The full variant resolves the enums to strings and carries the price list. Every')
        w('rule the bot depends on lives here.')
        w('')
        w('| Field | `GetAuctionSimple` | `GetAuction` (full) |')
        w('|---|---|---|')
        w('| `minimumBidType` | `1` | `"Percentage"` |')
        w('| `auctionEvaluationTypeCode` | `"BestPrice"` | plus `auctionEvaluationTypeDescription` |')
        w('| `minBidDifference` | *absent* | present, per price-list item |')
        w('')
        w('### Scalar configuration')
        w('')
        scalars = {k: v for k, v in full.items() if not isinstance(v, (list, dict))}
        w('```json')
        w(redact(json.dumps(scalars, indent=2, ensure_ascii=False)))
        w('```')
        w('')
        bl = full.get('biddingList') or []
        if bl:
            w('### Price list structure (`biddingList`) — lots and items')
            w('')
            w(f'{len(bl)} lot(s). First lot, with its items:')
            w('```json')
            w(redact(json.dumps(bl[0], indent=2, ensure_ascii=False))[:2600])
            w('```')
            w('')
            items = bl[0].get('biddingPriceListItems') or []
            if items and 'minBidDifference' in items[0]:
                mbd = items[0]['minBidDifference']
                base = items[0].get('itemInitialPrice')
                w(f'**CONFIRMED minimum-decrement rule.** `minimumBidType` is '
                  f'`"{full.get("minimumBidType")}"` and `minBidDifference` is `{mbd}`, i.e. '
                  f'{mbd}%. Against `itemInitialPrice` {base:,.0f} that is '
                  f'**{base * mbd / 100:,.2f}** — exactly the `minBid` the platform quoted when '
                  f'it rejected a bid (`"1.156.705,23 COP"`).')
                w('')
                w('The step is a percentage of the **initial** price, making it a fixed absolute')
                w('amount for the whole auction — *not* a percentage of the current best bid.')
                w('')
        bidders = full.get('bidders') or []
        if bidders:
            w('### Bidder roster (`bidders`) — anonymised by design')
            w('')
            w(f'{len(bidders)} bidders were registered for this auction. Competitor identity')
            w('fields are deliberately masked by the platform:')
            w('')
            w('```json')
            w(redact(json.dumps(bidders[0], indent=2, ensure_ascii=False)))
            w('```')
            w('')
            w('`companyName` is a generated pseudonym (`"Proveedor J"`), and `companyNIF`,')
            w('`companyContact` and `companyEmail` are all the sentinel `"Settings_Confidential"`.')
            w('')
            w('> **`companyCode`, however, is the real Colombian NIT** and is resolvable against')
            w('> public SECOP open data. The bot is therefore *capable* of de-anonymising every')
            w('> rival. It must not. Doing so subverts a deliberate platform privacy control and')
            w('> moves a bidder uncomfortably close to the coordination that Colombian law')
            w('> criminalises. Use the bidder *count* and the anonymous price signals only.')
            w('')

    # ---- 3. Auth headers
    w('## 3. Authentication')
    w('')

    # The HAR export stripped headers. Prove it by byte-accounting so nobody
    # mistakenly concludes the REST API is unauthenticated.
    w('### IMPORTANT: the capture was sanitised — REST auth headers were stripped')
    w('')
    w('The `headers` array below shows **no** `Cookie` and **no** `Authorization` header on')
    w('the `/v1/` REST calls. Do **not** conclude the API is unauthenticated. Byte-accounting')
    w('the requests proves headers were removed on export:')
    w('')
    w('| Request | Visible header bytes | Reported `headersSize` | Unaccounted |')
    w('|---|---:|---:|---:|')
    shown = 0
    for e in entries:
        r = e['request']
        if 'eauctions.api' not in r['url'] or '/v1/' not in r['url']:
            continue
        if r.get('headersSize', -1) <= 0:
            continue
        vis = sum(len(h['name']) + len(h['value']) + 4 for h in r['headers'])
        line = len(r['method']) + len(r['url']) + len(r['httpVersion']) + 4
        gap = r['headersSize'] - vis - line
        name = urlparse(r['url']).path.split('/')[-2:]
        w(f'| `{"/".join(name)[:40]}` | {vis} | {r["headersSize"]} | **{gap}** |')
        shown += 1
        if shown >= 5:
            break
    w('')
    w('Roughly 2.5 KB per request is missing. That is the size of a VORTAL/ASP.NET session')
    w('cookie jar. **DERIVED conclusion:** the auction REST API authenticates via session')
    w('cookies (and possibly a bearer token) that this capture does not contain.')
    w('')
    w('**Architectural consequence:** the client cannot authenticate with the JWT alone.')
    w('The JWT is only proven to authenticate the SignalR transport (`token` query param).')
    w('REST calls need the browser session cookie jar, which is why session bootstrap must')
    w('go through a real browser and export full storage state — not just a decoded token.')
    w('')
    w('**OPEN QUESTION:** confirm the exact REST auth mechanism by inspecting the live')
    w('requests in a fresh, unsanitised capture before implementing the client.')
    w('')
    w('### Headers that *were* preserved')
    w('')
    for e in entries:
        if 'eauctions.api' in e['request']['url'] and '/v1/' in e['request']['url']:
            w('Headers sent to the auction API (values redacted):')
            w('```http')
            for h in e['request']['headers']:
                n = h['name'].lower()
                if n.startswith(':'):
                    continue
                val = h['value']
                if n in SENSITIVE_HEADERS or 'token' in n:
                    val = '<REDACTED>'
                else:
                    val = redact(val)
                w(f'{h["name"]}: {val[:120]}')
            w('```')
            w('')
            break

    # ---- 3b. Audit trail
    audit = None
    for e in entries:
        if 'GetEventLogs' in e['request']['url']:
            try:
                audit = json.loads(e['response']['content']['text'])
            except Exception:
                pass
            if audit:
                break
    if audit:
        w('## 3b. The audit trail — every action is recorded, including failures')
        w('')
        w('`GET /v1/audit/GetEventLogs` is a DataTables-style endpoint '
          '(`draw`, `recordsTotal`, `recordsFiltered`, `data`). It is the authoritative '
          'record of what happened, and therefore the reconciliation source after a '
          'dropped connection.')
        w('')
        rows = audit.get('data') or []
        w(f'Example rows ({len(rows)} of {audit.get("recordsTotal")} returned):')
        w('')
        w('```json')
        w(redact(json.dumps(rows[:3], indent=2, ensure_ascii=False)))
        w('```')
        w('')
        w('### Two consequences that shape the design')
        w('')
        w('**1. A failed `ValidateBid` writes a permanent, entity-visible audit row.**')
        w('')
        w('This is counter-intuitive and it is the single most important operational fact')
        w('in this document, so here is the reasoning in full:')
        w('')
        w('- `SubmitBid` was called **zero** times across all five captures.')
        w('- `ValidateBid` was called **exactly twice**, and both calls were rejected.')
        w('- The audit log contains **exactly two** `Logs_Search_NewBid` rows reading')
        w('  `"Error cuando presentado el lance. Problema: ..."`, in the same order.')
        w('')
        w('Since no submit ever happened, those rows can only have come from the failed')
        w('validations. **CONFIRMED: validation is not free.** A rejected `ValidateBid`')
        w('leaves a permanent record that the contracting entity can read.')
        w('')
        w('The design consequences are significant:')
        w('')
        w('- The bot **must run a local legality check before calling `ValidateBid`**, so it')
        w('  never spends an audit-visible attempt on a bid it could have known was illegal.')
        w('  See `fixtures/bid-validation-vectors.json` for that check.')
        w('- The bot **must budget** validation attempts per auction and treat repeated')
        w('  rejections as a fault worth alerting on, not as a retry loop.')
        w('- `ValidateBid` still precedes `SubmitBid`, but for a narrower reason than')
        w('  "validation is free": a rejected *submit* is at least as visible, and')
        w('  validating first is the only way to learn the rule without guessing.')
        w('')
        w('**Not established:** whether a *successful* `ValidateBid` is also logged. We never')
        w('produced one. The subtype `Logs_Search_NewBid` is shared, and a separate')
        w('`Logs_Search_SubmitBidding` ("Presentar lances") exists in the vocabulary, so the')
        w('log alone cannot distinguish validate from submit. Treat as an OPEN QUESTION.')
        w('')
        w('**2. The bidder\'s IP address is recorded on every action** (`ipAddress` field).')
        w('The operator should know their network origin is attributable. The honest')
        w('posture is to run the bot from a stable, attributable connection. Rotating or')
        w('anonymising IPs would serve no legitimate purpose here and would look evasive in')
        w('exactly the record a dispute would examine.')
        w('')
        w('`eventHistoryTypeCode` and `eventHistorySubTypeCode` are localization keys '
          '(e.g. `Logs_Search_Bid`, `Logs_Search_NewBid`, `Logs_Search_StartBidding`) — '
          'resolve them via the vocabulary in `09-platform-vocabulary.md`.')
        w('')
        w('The presence of `Logs_Search_StartBidding` ("Comenzar Lances") confirms that '
          '`POST /v1/audit/SetStartBiddingAudit` must be called before bidding begins.')
        w('')

    # ---- 4. SignalR protocol
    w('## 4. SignalR realtime protocol')
    w('')
    sr = collections.OrderedDict()
    for e in entries:
        u = e['request']['url']
        if '/signalr/' not in u:
            continue
        path = urlparse(u).path.split('/signalr/')[-1]
        qs = parse_qs(urlparse(u).query)
        if path not in sr:
            sr[path] = {'count': 0, 'qs': qs, 'example': e}
        sr[path]['count'] += 1
    w('| SignalR endpoint | Calls | Transport params |')
    w('|---|---:|---|')
    for p, info in sr.items():
        params = ', '.join(f'{k}' for k in info['qs'] if k != 'token')
        w(f'| `{p}` | {info["count"]} | {params} |')
    w('')

    # hub invocations
    w('### Hub invocations (client -> server, via `/signalr/send`)')
    w('')
    invocations = collections.Counter()
    for e in entries:
        if '/signalr/send' not in e['request']['url']:
            continue
        pd = e['request'].get('postData', {}).get('text', '')
        if not pd:
            continue
        try:
            payload = json.loads(unquote(pd.replace('data=', '')))
            invocations[(payload.get('H'), payload.get('M'),
                         json.dumps(payload.get('A'))[:80])] += 1
        except Exception:
            pass
    w('| Hub | Method | Args | Count |')
    w('|---|---|---|---:|')
    for (hub, m, a), c in invocations.most_common():
        a_disp = re.sub(r'"[0-9a-f]{8}-[0-9a-f-]{27,}"', '"{auctionId}"', a or '')
        w(f'| `{hub}` | `{m}` | `{a_disp}` | {c} |')
    w('')

    # server -> client messages
    w('### Server -> client messages (from `/signalr/poll` and `/connect` responses)')
    w('')
    server_msgs = collections.OrderedDict()
    for e in entries:
        if '/signalr/' not in e['request']['url']:
            continue
        rc = e['response'].get('content', {}).get('text', '')
        if not rc:
            continue
        try:
            data = json.loads(rc)
        except Exception:
            continue
        for m in (data.get('M') or []):
            if not isinstance(m, dict):
                continue
            key = (m.get('H'), m.get('M'))
            if key not in server_msgs:
                server_msgs[key] = m
    w('| Hub | Method | Example payload |')
    w('|---|---|---|')
    for (hub, meth), m in server_msgs.items():
        ex = redact(json.dumps(m.get('A'), ensure_ascii=False))
        ex = re.sub(r'"[0-9a-f]{8}-[0-9a-f-]{27,}"', '"{uuid}"', ex)
        ex_cell = ex[:300].replace('|', '\\|')
        w(f'| `{hub}` | `{meth}` | `{ex_cell}` |')
    w('')

    w('### Full detail of distinct server->client payloads')
    w('')
    for (hub, meth), m in server_msgs.items():
        w(f'#### `{hub}.{meth}`')
        w('```json')
        w(redact(json.dumps(m.get('A'), indent=2, ensure_ascii=False))[:3000])
        w('```')
        w('')

    # ---- 5. Timing / polling cadence
    w('## 5. Polling cadence & timing observations')
    w('')
    polls = [e for e in entries if '/signalr/poll' in e['request']['url']]
    if polls:
        w(f'- `/signalr/poll` calls: **{len(polls)}**')
        durs = sorted(e['time'] for e in polls)
        w(f'- poll durations ms: min={durs[0]:.0f} p50={durs[len(durs)//2]:.0f} max={durs[-1]:.0f}')
    clocks = [e for e in entries
              if '/signalr/send' in e['request']['url']
              and 'RequestClock' in unquote(e['request'].get('postData', {}).get('text', ''))]
    w(f'- `auction.RequestClock` invocations: **{len(clocks)}**')
    if len(clocks) > 2:
        import datetime
        ts = [datetime.datetime.fromisoformat(e['startedDateTime'].replace('Z', '+00:00')) for e in clocks]
        gaps = [(ts[i + 1] - ts[i]).total_seconds() for i in range(len(ts) - 1)]
        gaps = [g for g in gaps if 0 < g < 120]
        if gaps:
            gaps.sort()
            w(f'- clock request interval s: min={gaps[0]:.1f} p50={gaps[len(gaps)//2]:.1f} max={gaps[-1]:.1f}')
    w('')

    # ---- 6. Portal endpoints (SECOP II main site) that matter
    w('## 6. SECOP II portal endpoints (tender discovery / workspace)')
    w('')
    portal = collections.Counter()
    for e in entries:
        u = e['request']['url']
        if 'www.secop.gov.co' in u and not is_noise(u):
            portal[e['request']['method'] + ' ' + urlparse(u).path] += 1
    for k, c in portal.most_common(60):
        w(f'- `{k}` ({c}x)')
    w('')

    # ---- 7. Login / STS flow
    w('## 7. Identity / login flow (community.secop.gov.co)')
    w('')
    login = []
    for e in entries:
        u = e['request']['url']
        if 'community.secop.gov.co' in u and not is_noise(u):
            p = urlparse(u).path
            if any(k in p.lower() for k in ('sts', 'login', 'issue', 'sign', 'auth', 'token')):
                login.append((e['request']['method'], p, e['response']['status']))
    for m, p, s in dict.fromkeys(login):
        w(f'- `{m} {p}` -> {s}')
    w('')
    recaptcha = sum(1 for e in entries if 'recaptcha' in e['request']['url'].lower())
    w(f'- reCAPTCHA-related requests observed: **{recaptcha}** '
      f'(login is CAPTCHA-protected -> headless-only auth is not reliable)')
    w('')

    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print(f'wrote {OUT} ({len(chr(10).join(out))} bytes)')


main()
