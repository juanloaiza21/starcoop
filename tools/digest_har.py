#!/usr/bin/env python3
"""Digest SECOP II HAR captures into a compact API contract for analysis.

Redacts JWTs/cookies so the output is safe to reason over and to commit.
"""
import json, glob, os, re, sys, collections
from urllib.parse import urlparse, parse_qs, unquote

HAR_DIR = sys.argv[1]
OUT = sys.argv[2]

JWT_RE = re.compile(r'eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}')
SENSITIVE_HEADERS = {'authorization', 'cookie', 'set-cookie', 'x-xsrf-token'}


def redact(s):
    if not isinstance(s, str):
        return s
    return JWT_RE.sub('<JWT_REDACTED>', s)


def is_noise(url):
    """Static assets, telemetry, third-party."""
    noise_hosts = ('gstatic.com', 'youtube.com', 'google.com', 'googletagmanager',
                   'doubleclick', 'ytimg.com', 'googleapis.com', 'gravatar')
    if any(h in url for h in noise_hosts):
        return True
    if '/StaticContent/' in url:
        return True
    if re.search(r'\.(js|css|png|jpg|jpeg|gif|svg|woff2?|ttf|ico|map|eot)(_v\d+)?($|\?)', url, re.I):
        return True
    return False


def main():
    entries = []
    for f in sorted(glob.glob(os.path.join(HAR_DIR, '*.har'))):
        try:
            d = json.load(open(f, encoding='utf-8'))
        except Exception as e:
            print(f'skip {f}: {e}', file=sys.stderr)
            continue
        for e in d['log']['entries']:
            e['_src'] = os.path.basename(f)
            entries.append(e)

    entries.sort(key=lambda e: e.get('startedDateTime', ''))

    out = []
    w = out.append

    w('# SECOP II e-Auction — Reverse-Engineered API Contract')
    w('')
    w('Digested from 5 HAR captures of a live `subasta inversa electronica`.')
    w('All JWTs/cookies redacted. Generated by `digest_har.py`.')
    w('')

    # ---- 1. Hosts
    hosts = collections.Counter()
    for e in entries:
        h = urlparse(e['request']['url']).netloc
        if not is_noise(e['request']['url']):
            hosts[h] += 1
    w('## 1. Hosts in play')
    w('')
    w('| Host | Non-static requests | Role |')
    w('|---|---:|---|')
    roles = {
        'community.secop.gov.co': 'Identity / STS — issues the JWT, hosts login + reCAPTCHA',
        'www.secop.gov.co': 'SECOP II main portal (CO1BusinessLine) — tender workspace',
        'subastas.secop.gov.co': 'e-Auction engine — REST API + SignalR realtime hub',
    }
    for h, c in hosts.most_common():
        w(f'| `{h}` | {c} | {roles.get(h, "")} |')
    w('')

    # ---- 2. REST endpoints on the auction API
    w('## 2. e-Auction REST API surface')
    w('')
    seen = collections.OrderedDict()
    for e in entries:
        u = e['request']['url']
        if 'eauctions.api' not in u:
            continue
        if '/signalr/' in u:
            continue
        path = urlparse(u).path.replace('/eauctions.api', '')
        key = (e['request']['method'], re.sub(r'/[0-9a-f]{8}-[0-9a-f-]{27,}', '/{auctionId}', path))
        key = (key[0], re.sub(r'/\d{6,}', '/{companyCode}', key[1]))
        if key not in seen:
            seen[key] = e

    for (method, path), e in seen.items():
        w(f'### `{method} {path}`')
        w('')
        qs = parse_qs(urlparse(e['request']['url']).query)
        if qs:
            w('Query params: ' + ', '.join(
                f'`{k}={"<JWT>" if k == "token" else redact(v[0])[:60]}`' for k, v in qs.items()))
            w('')
        pd = e['request'].get('postData', {}).get('text', '')
        if pd:
            w('Request body:')
            w('```json')
            try:
                w(json.dumps(json.loads(redact(pd)), indent=2, ensure_ascii=False)[:3000])
            except Exception:
                w(redact(unquote(pd))[:2000])
            w('```')
            w('')
        rc = e['response'].get('content', {}).get('text', '')
        if rc:
            w(f'Response ({e["response"]["status"]}):')
            w('```json')
            try:
                w(json.dumps(json.loads(redact(rc)), indent=2, ensure_ascii=False)[:4500])
            except Exception:
                w(redact(rc)[:2000])
            w('```')
            w('')

    # ---- 3. Auth headers
    w('## 3. Authentication')
    w('')
    for e in entries:
        if 'eauctions.api' in e['request']['url'] and '/v1/' in e['request']['url']:
            w('Headers sent to the auction API (values redacted):')
            w('```http')
            for h in e['request']['headers']:
                n = h['name'].lower()
                if n.startswith(':'):
                    continue
                val = h['value']
                if n in SENSITIVE_HEADERS or 'token' in n:
                    val = '<REDACTED>'
                else:
                    val = redact(val)
                w(f'{h["name"]}: {val[:120]}')
            w('```')
            w('')
            break

    # ---- 4. SignalR protocol
    w('## 4. SignalR realtime protocol')
    w('')
    sr = collections.OrderedDict()
    for e in entries:
        u = e['request']['url']
        if '/signalr/' not in u:
            continue
        path = urlparse(u).path.split('/signalr/')[-1]
        qs = parse_qs(urlparse(u).query)
        if path not in sr:
            sr[path] = {'count': 0, 'qs': qs, 'example': e}
        sr[path]['count'] += 1
    w('| SignalR endpoint | Calls | Transport params |')
    w('|---|---:|---|')
    for p, info in sr.items():
        params = ', '.join(f'{k}' for k in info['qs'] if k != 'token')
        w(f'| `{p}` | {info["count"]} | {params} |')
    w('')

    # hub invocations
    w('### Hub invocations (client -> server, via `/signalr/send`)')
    w('')
    invocations = collections.Counter()
    for e in entries:
        if '/signalr/send' not in e['request']['url']:
            continue
        pd = e['request'].get('postData', {}).get('text', '')
        if not pd:
            continue
        try:
            payload = json.loads(unquote(pd.replace('data=', '')))
            invocations[(payload.get('H'), payload.get('M'),
                         json.dumps(payload.get('A'))[:80])] += 1
        except Exception:
            pass
    w('| Hub | Method | Args | Count |')
    w('|---|---|---|---:|')
    for (hub, m, a), c in invocations.most_common():
        a_disp = re.sub(r'"[0-9a-f]{8}-[0-9a-f-]{27,}"', '"{auctionId}"', a or '')
        w(f'| `{hub}` | `{m}` | `{a_disp}` | {c} |')
    w('')

    # server -> client messages
    w('### Server -> client messages (from `/signalr/poll` and `/connect` responses)')
    w('')
    server_msgs = collections.OrderedDict()
    for e in entries:
        if '/signalr/' not in e['request']['url']:
            continue
        rc = e['response'].get('content', {}).get('text', '')
        if not rc:
            continue
        try:
            data = json.loads(rc)
        except Exception:
            continue
        for m in (data.get('M') or []):
            if not isinstance(m, dict):
                continue
            key = (m.get('H'), m.get('M'))
            if key not in server_msgs:
                server_msgs[key] = m
    w('| Hub | Method | Example payload |')
    w('|---|---|---|')
    for (hub, meth), m in server_msgs.items():
        ex = redact(json.dumps(m.get('A'), ensure_ascii=False))
        ex = re.sub(r'"[0-9a-f]{8}-[0-9a-f-]{27,}"', '"{uuid}"', ex)
        ex_cell = ex[:300].replace('|', '\\|')
        w(f'| `{hub}` | `{meth}` | `{ex_cell}` |')
    w('')

    w('### Full detail of distinct server->client payloads')
    w('')
    for (hub, meth), m in server_msgs.items():
        w(f'#### `{hub}.{meth}`')
        w('```json')
        w(json.dumps(m.get('A'), indent=2, ensure_ascii=False)[:3000])
        w('```')
        w('')

    # ---- 5. Timing / polling cadence
    w('## 5. Polling cadence & timing observations')
    w('')
    polls = [e for e in entries if '/signalr/poll' in e['request']['url']]
    if polls:
        w(f'- `/signalr/poll` calls: **{len(polls)}**')
        durs = sorted(e['time'] for e in polls)
        w(f'- poll durations ms: min={durs[0]:.0f} p50={durs[len(durs)//2]:.0f} max={durs[-1]:.0f}')
    clocks = [e for e in entries
              if '/signalr/send' in e['request']['url']
              and 'RequestClock' in unquote(e['request'].get('postData', {}).get('text', ''))]
    w(f'- `auction.RequestClock` invocations: **{len(clocks)}**')
    if len(clocks) > 2:
        import datetime
        ts = [datetime.datetime.fromisoformat(e['startedDateTime'].replace('Z', '+00:00')) for e in clocks]
        gaps = [(ts[i + 1] - ts[i]).total_seconds() for i in range(len(ts) - 1)]
        gaps = [g for g in gaps if 0 < g < 120]
        if gaps:
            gaps.sort()
            w(f'- clock request interval s: min={gaps[0]:.1f} p50={gaps[len(gaps)//2]:.1f} max={gaps[-1]:.1f}')
    w('')

    # ---- 6. Portal endpoints (SECOP II main site) that matter
    w('## 6. SECOP II portal endpoints (tender discovery / workspace)')
    w('')
    portal = collections.Counter()
    for e in entries:
        u = e['request']['url']
        if 'www.secop.gov.co' in u and not is_noise(u):
            portal[e['request']['method'] + ' ' + urlparse(u).path] += 1
    for k, c in portal.most_common(60):
        w(f'- `{k}` ({c}x)')
    w('')

    # ---- 7. Login / STS flow
    w('## 7. Identity / login flow (community.secop.gov.co)')
    w('')
    login = []
    for e in entries:
        u = e['request']['url']
        if 'community.secop.gov.co' in u and not is_noise(u):
            p = urlparse(u).path
            if any(k in p.lower() for k in ('sts', 'login', 'issue', 'sign', 'auth', 'token')):
                login.append((e['request']['method'], p, e['response']['status']))
    for m, p, s in dict.fromkeys(login):
        w(f'- `{m} {p}` -> {s}')
    w('')
    recaptcha = sum(1 for e in entries if 'recaptcha' in e['request']['url'].lower())
    w(f'- reCAPTCHA-related requests observed: **{recaptcha}** '
      f'(login is CAPTCHA-protected -> headless-only auth is not reliable)')
    w('')

    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print(f'wrote {OUT} ({len(chr(10).join(out))} bytes)')


main()
